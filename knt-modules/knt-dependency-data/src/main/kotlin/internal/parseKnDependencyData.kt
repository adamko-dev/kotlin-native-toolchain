//region TOML syntax

/** A position in the parsed file, used in error messages. */
private data class Position(
  val source: String,
  val line: Int,
  val text: String,
)

private fun Position.parseError(message: String): Nothing =
  error("Invalid $source line $line: $message. Line: '$text'")

/** The punctuation characters in the supported TOML subset. */
private enum class Punct(val char: Char) {
  OpenBracket('['),
  CloseBracket(']'),
  OpenBrace('{'),
  CloseBrace('}'),
  Equals('='),
  Comma(','),
  ;

  companion object {
    fun of(char: Char): Punct? = entries.find { it.char == char }
  }
}

private sealed interface Token {
  val position: Position

  /** One of `[ ] { } = ,`. */
  data class Punctuation(val punct: Punct, override val position: Position) : Token

  /** A string, without the quotes. */
  data class Str(val value: String, override val position: Position) : Token

  /** A bare key, or an integer. */
  data class Bare(val value: String, override val position: Position) : Token

  /** Ends a key/value pair or table header. Ignored inside arrays. */
  data class Newline(override val position: Position) : Token
}

private val tokenRegex =
  Regex("""(?<comment>#.*)|"(?<string>[^"\\]*)"|(?<bare>[\w-]+)|(?<punct>[\[\]{}=,])|(?<other>\S)""")

/** Split [content] into tokens. Comments and whitespace are dropped, and every line ends with a [Token.Newline]. */
private fun tokenize(source: String, content: String): List<Token> =
  content.lines().flatMapIndexed { index, text ->
    val position = Position(source = source, line = index + 1, text = text.trim())
    tokenizeLine(text, position)
  }

/** Split one line into tokens, ending with a [Token.Newline]. */
private fun tokenizeLine(text: String, position: Position): List<Token> {
  val matches = tokenRegex.findAll(text).toList()
  val tokens = matches.mapNotNull { match -> toToken(match, position) }
  return tokens + Token.Newline(position)
}

/** Convert a [tokenRegex] match to a [Token]. Returns `null` for comments. */
private fun toToken(match: MatchResult, position: Position): Token? {
  val groups = match.groups
  val string = groups["string"]
  return when {
    groups["comment"] != null -> null
    string != null            -> Token.Str(string.value, position)
    groups["bare"] != null    -> Token.Bare(match.value, position)
    groups["punct"] != null   -> toPunctuation(match.value.single(), position)
    else                      -> position.parseError("unexpected '${match.value}'")
  }
}

private fun toPunctuation(char: Char, position: Position): Token.Punctuation {
  val punct = Punct.of(char)
    ?: position.parseError("unexpected '$char'")
  return Token.Punctuation(punct, position)
}

private sealed interface TomlValue {
  val position: Position

  data class Str(val value: String, override val position: Position) : TomlValue
  data class Integer(val value: Long, override val position: Position) : TomlValue
  data class Array(val items: List<TomlValue>, override val position: Position) : TomlValue
  data class InlineTable(val entries: Map<String, TomlValue>, override val position: Position) : TomlValue
}

/** A `[<name>]` table, and its entries. */
private data class TomlTable(
  val name: String,
  val position: Position,
  val entries: Map<String, TomlValue>,
)

/** The root table entries, and the tables that follow. */
private data class TomlDocument(
  val root: Map<String, TomlValue>,
  val tables: List<TomlTable>,
)

/**
 * A recursive descent parser for the supported TOML subset:
 *
 * ```text
 * document    := keyValues table*
 * table       := '[' bare ']' newline keyValues
 * keyValues   := (key '=' value newline)*
 * key         := bare | string
 * value       := string | integer | array | inlineTable
 * array       := '[' (value (',' value)* ','?)? ']'     newlines are allowed
 * inlineTable := '{' (key '=' value (',' key '=' value)*)? '}'
 * ```
 */
private class TomlSubsetParser(private val tokens: List<Token>) {
  private var index = 0

  fun parseDocument(): TomlDocument {
    val root = parseKeyValues()
    val tables = buildList {
      while (peek() != null) {
        add(parseTable())
      }
    }
    return TomlDocument(root, tables)
  }

  private fun parseTable(): TomlTable {
    val open = expectPunct(Punct.OpenBracket)
    val name = when (val token = next("a table name")) {
      is Token.Bare -> token
      else          -> token.position.parseError("expected a table name")
    }
    expectPunct(Punct.CloseBracket)
    expectEndOfLine()

    val entries = parseKeyValues()
    return TomlTable(name.value, open.position, entries)
  }

  /** Parse key/value pairs, until the next table header or the end of the file. */
  private fun parseKeyValues(): Map<String, TomlValue> {
    val keyValues = buildList {
      while (true) {
        skipNewlines()
        val token = peek()
        if (token == null || token.isPunct(Punct.OpenBracket)) {
          break
        }
        add(parseKeyValue())
        expectEndOfLine()
      }
    }
    return keyValues.toUniqueKeyMap()
  }

  private fun parseKeyValue(): Pair<String, TomlValue> {
    val key = when (val token = next("a key")) {
      is Token.Bare -> token.value
      is Token.Str  -> token.value
      else          -> token.position.parseError("expected a key")
    }
    expectPunct(Punct.Equals)
    val value = parseValue()
    return key to value
  }

  private fun parseValue(): TomlValue {
    return when (val token = next("a value")) {
      is Token.Str         -> TomlValue.Str(token.value, token.position)
      is Token.Bare        -> parseInteger(token)
      is Token.Punctuation -> when (token.punct) {
        Punct.OpenBracket -> parseArray(token.position)
        Punct.OpenBrace   -> parseInlineTable(token.position)
        Punct.CloseBracket,
        Punct.CloseBrace,
        Punct.Equals,
        Punct.Comma       -> token.position.parseError("expected a value")
      }

      is Token.Newline     -> token.position.parseError("expected a value")
    }
  }

  private fun parseInteger(token: Token.Bare): TomlValue.Integer {
    val value = token.value.toLongOrNull()
      ?: token.position.parseError("expected a value, but was '${token.value}'")
    return TomlValue.Integer(value, token.position)
  }

  private fun parseArray(position: Position): TomlValue.Array {
    val items = buildList {
      while (true) {
        skipNewlines()
        if (peekIsPunct(Punct.CloseBracket)) {
          break
        }
        add(parseValue())
        skipNewlines()
        if (!consumePunct(Punct.Comma)) {
          break
        }
      }
    }
    skipNewlines()
    expectPunct(Punct.CloseBracket)
    return TomlValue.Array(items, position)
  }

  private fun parseInlineTable(position: Position): TomlValue.InlineTable {
    val keyValues = buildList {
      val isEmpty = consumePunct(Punct.CloseBrace)
      if (!isEmpty) {
        do {
          add(parseKeyValue())
        } while (consumePunct(Punct.Comma))
        expectPunct(Punct.CloseBrace)
      }
    }
    return TomlValue.InlineTable(keyValues.toUniqueKeyMap(), position)
  }

  /** Convert key/value pairs to a map, and fail if a key is used more than once. */
  private fun List<Pair<String, TomlValue>>.toUniqueKeyMap(): Map<String, TomlValue> =
    fold(emptyMap()) { acc, (key, value) ->
      if (key in acc) {
        value.position.parseError("duplicate key '$key'")
      }
      acc + (key to value)
    }

  /** The next token, without consuming it. Returns `null` at the end of the file. */
  private fun peek(): Token? = tokens.getOrNull(index)

  /** Consume the next token. */
  private fun next(expected: String): Token {
    val token = peek()
      ?: tokens.last().position.parseError("expected $expected, but was end of file")
    index++
    return token
  }

  private fun peekIsPunct(punct: Punct): Boolean {
    val token = peek()
    return token != null && token.isPunct(punct)
  }

  /** Consume the next token if it is [punct]. */
  private fun consumePunct(punct: Punct): Boolean {
    if (!peekIsPunct(punct)) {
      return false
    }
    index++
    return true
  }

  /** Consume the next token, and fail if it is not [punct]. */
  @IgnorableReturnValue
  private fun expectPunct(punct: Punct): Token {
    val token = next("'${punct.char}'")
    if (!token.isPunct(punct)) {
      token.position.parseError("expected '${punct.char}'")
    }
    return token
  }

  private fun expectEndOfLine() {
    when (val token = peek()) {
      null, is Token.Newline -> {}
      else                   -> token.position.parseError("expected end of line")
    }
  }

  private fun skipNewlines() {
    while (peek() is Token.Newline) {
      index++
    }
  }

  private fun Token.isPunct(punct: Punct): Boolean =
    when (this) {
      is Token.Punctuation -> this.punct == punct
      else                 -> false
    }
}

