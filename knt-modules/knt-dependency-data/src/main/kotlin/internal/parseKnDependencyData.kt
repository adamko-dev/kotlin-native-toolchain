package dev.adamko.kntoolchain.tools.data.internal

import dev.adamko.kntoolchain.tools.data.KnBuildPlatform
import dev.adamko.kntoolchain.tools.data.KnCompileTarget
import dev.adamko.kntoolchain.tools.data.KnpDependency

/**
 * The content of a `knpdeps-<version>.toml` file.
 *
 * @see parseKnDependencyData
 */
internal sealed interface ParsedKnDependencyData {
  /** The Kotlin version the data is for. */
  val kotlinVersion: String
  /** The dependencies required by each compile target, grouped by build platform. */
  val dependencies: Map<KnBuildPlatform, Map<KnCompileTarget, Set<KnpDependency>>>
}

/**
 * Parse the TOML content of a `knpdeps-<version>.toml` file generated by `KnpDataGenTask`.
 *
 * The files are valid TOML, but this parser only supports a subset:
 * strings without escapes, integers, arrays, inline tables, and tables.
 * The format specification is documented on `createKnDependencyDataResource()` in `KnpDataGenTask.kt`.
 *
 * @param source The name of the parsed file, used in error messages.
 */
internal fun parseKnDependencyData(source: String, content: String): ParsedKnDependencyData {
  val tokens = tokenize(source, content)
  val document = TomlSubsetParser(tokens).parseDocument()

  val kotlinVersion = parseRoot(source, document.root)

  checkNoDuplicateTables(source, document.tables)

  val artifactsTable = document.tables.find { it.name == ARTIFACTS_TABLE }
  val artifacts = if (artifactsTable != null) {
    parseArtifacts(artifactsTable)
  } else {
    emptyMap()
  }

  val buildPlatforms = KnBuildPlatform.allPlatforms.associateBy { "${it.family.name}-${it.arch.name}" }
  val compileTargets = KnCompileTarget.allTargets.associateBy { it.name }

  val buildPlatformTables = document.tables.filter { it.name != ARTIFACTS_TABLE }

  val dependencies = buildPlatformTables.associate { table ->
    val buildPlatform = buildPlatforms[table.name]
      ?: table.position.parseError("unknown build platform '${table.name}'")
    val buildPlatformDependencies = parseBuildPlatform(table, compileTargets, artifacts)
    buildPlatform to buildPlatformDependencies
  }

  return ParsedKnDependencyDataImpl(kotlinVersion, dependencies)
}

private const val FORMAT_KEY = "format"
private const val FORMAT_VERSION = 1L
private const val KOTLIN_VERSION_KEY = "kotlinVersion"
private const val ARTIFACTS_TABLE = "artifacts"
private const val SAME_AS_KEY = "sameAs"


private data class ParsedKnDependencyDataImpl(
  /** The Kotlin version the data is for. */
  override val kotlinVersion: String,
  /** The dependencies required by each compile target, grouped by build platform. */
  override val dependencies: Map<KnBuildPlatform, Map<KnCompileTarget, Set<KnpDependency>>>,
) : ParsedKnDependencyData


//region Data mapping

/**
 * The root table must contain only `format = 1` and `kotlinVersion = "<version>"`.
 *
 * @returns the Kotlin version.
 */
private fun parseRoot(source: String, root: Map<String, TomlValue>): String {
  val format = root[FORMAT_KEY]
    ?: error("Invalid $source: missing '$FORMAT_KEY = $FORMAT_VERSION'")
  val formatVersion = when (format) {
    is TomlValue.Integer -> format.value
    else                 -> format.position.parseError("expected $FORMAT_KEY to be an integer")
  }
  if (formatVersion != FORMAT_VERSION) {
    format.position.parseError("unsupported $FORMAT_KEY, expected '$FORMAT_VERSION'")
  }

  root.forEach { (key, value) ->
    if (key != FORMAT_KEY && key != KOTLIN_VERSION_KEY) {
      value.position.parseError("unexpected key '$key'")
    }
  }

  val kotlinVersion = root[KOTLIN_VERSION_KEY]
    ?: error("Invalid $source: missing '$KOTLIN_VERSION_KEY'")
  return kotlinVersion.string()
}

/** Fail if any table name is used more than once, reporting every duplicate. */
private fun checkNoDuplicateTables(source: String, tables: List<TomlTable>) {
  val lineNumbersByName = tables.groupBy(
    keySelector = { it.name },
    valueTransform = { it.position.line },
  )
  val duplicateTables = lineNumbersByName.filterValues { it.size > 1 }

  if (duplicateTables.isNotEmpty()) {
    val duplicates = duplicateTables.entries.joinToString { (name, lineNumbers) ->
      "'$name' (lines ${lineNumbers.joinToString()})"
    }
    error("Invalid $source: duplicate tables $duplicates")
  }
}

/** Parse `"<coordinates>" = "<artifact>"` entries. */
private fun parseArtifacts(table: TomlTable): Map<String, String> =
  table.entries.mapValues { (_, artifact) -> artifact.string() }

/** Parse `<compile target> = [...]` and `<compile target> = { sameAs = "<compile target>" }` entries. */
private fun parseBuildPlatform(
  table: TomlTable,
  compileTargets: Map<String, KnCompileTarget>,
  artifacts: Map<String, String>,
): Map<KnCompileTarget, Set<KnpDependency>> {

  fun findCompileTarget(name: String, position: Position): KnCompileTarget {
    return compileTargets[name]
      ?: position.parseError("unknown compile target '$name'")
  }

  val entries: Map<KnCompileTarget, TomlValue> =
    table.entries.entries.associate { (name, value) ->
      findCompileTarget(name, value.position) to value
    }

  // First, parse the targets with an array of dependencies...
  val dependencies =
    entries.entries.fold(emptyMap<KnCompileTarget, Set<KnpDependency>>()) { acc, (compileTarget, value) ->
      when (value) {
        is TomlValue.Array -> acc + (compileTarget to parseDependencies(value, artifacts))
        else               -> acc
      }
    }

  // ...then resolve `sameAs`, which may refer to targets declared before or after it.
  return entries.mapValues { (compileTarget, value) ->
    when (value) {
      is TomlValue.Array -> {
        dependencies.getValue(compileTarget)
      }

      else               -> {
        val sameAs = value.sameAs()
        val sameAsTarget = findCompileTarget(sameAs.string(), sameAs.position)
        dependencies[sameAsTarget]
          ?: sameAs.position.parseError("'${sameAs.string()}' must be a compile target with dependencies")
      }
    }
  }
}

/** Convert an array of dependency coordinates to [KnpDependency]s. */
private fun parseDependencies(array: TomlValue.Array, artifacts: Map<String, String>): Set<KnpDependency> {
  if (array.items.isEmpty()) {
    array.position.parseError("array must not be empty")
  }

  return array.items.mapTo(linkedSetOf()) { item ->
    val coord = item.string()
    try {
      KnpDependency(coord = coord, artifact = artifacts[coord])
    } catch (e: IllegalStateException) {
      item.position.parseError(e.message ?: "invalid coordinates")
    }
  }
}

/** Get the value of `{ sameAs = "<compile target>" }`. */
private fun TomlValue.sameAs(): TomlValue {
  val table = when (this) {
    is TomlValue.InlineTable -> this
    else                     ->
      position.parseError("expected an array of dependencies, or '{ $SAME_AS_KEY = \"<compile target>\" }'")
  }

  table.entries.keys.forEach { key ->
    if (key != SAME_AS_KEY) {
      position.parseError("unexpected key '$key'")
    }
  }

  val sameAs = table.entries[SAME_AS_KEY]
    ?: position.parseError("missing '$SAME_AS_KEY'")
  return sameAs
}

private fun TomlValue.string(): String =
  when (this) {
    is TomlValue.Str -> value
    else             -> position.parseError("expected a string")
  }

